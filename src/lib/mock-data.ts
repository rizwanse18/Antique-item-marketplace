export const getSeller = (id: string): Seller =>
  SELLERS.find((s) => s.id === id) ?? SELLERS[0];

export const getItemBySlug = (slug: string): Item | undefined =>
  ITEMS.find((i) => i.slug === slug);

export const isLive = (item: Item) =>
  item.saleType !== "buynow" && new Date(item.endsAt).getTime() > Date.now();

export const formatMoney = (n: number) =>
  "$" + n.toLocaleString("en-US", { maximumFractionDigits: 0 });

export const minIncrement = (bid: number) => Math.max(10, Math.round(bid * 0.05));

export const relatedItems = (item: Item, limit = 3): Item[] =>
  ITEMS.filter(
    (i) => i.id !== item.id && (i.categorySlug === item.categorySlug || i.origin === item.origin)
  ).slice(0, limit);

export const timeAgo = (ts: number) => {
  const diff = Date.now() - ts;
  const m = Math.floor(diff / 60000);
  if (m < 1) return "just now";
  if (m < 60) return m + "m ago";
  const h = Math.floor(m / 60);
  if (h < 24) return h + "h ago";
  const d = Math.floor(h / 24);
  return d + "d ago";
};